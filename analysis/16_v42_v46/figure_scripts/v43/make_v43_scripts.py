"""One-time generator of the v43 figure scripts: each v42 main-figure script copied here under its final figure number,
with the type one step larger (cns_style.apply_large; every literal size mapped by BIG, nothing below 6 pt). Layout fixes
for the larger type were then made by hand in the copies, so do not rerun this over them."""
import re
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = {2: ("v42/make_fig2.py", "Fig2"), 3: ("v39/make_fig2.py", "Fig2"), 4: ("v39/make_fig3.py", "Fig3"),
       5: ("v39/make_fig4.py", "Fig4"), 6: ("v40/make_fig6.py", "Fig6"), 7: ("v41/make_fig7.py", "Fig7")}
BIG = {4.6: 6.0, 4.8: 6.0, 4.9: 6.0, 5.0: 6.0, 5.2: 6.2, 5.4: 6.3, 5.6: 6.5, 6.0: 7.0, 6.5: 7.5, 6.8: 7.8, 7.0: 8.0, 8.0: 9.0}
seen = Counter()


def big(m):
    v = float(m.group(2)); seen[v] += 1
    return f"{m.group(1)}={BIG[v]:g}"


for n, (src, stem) in SRC.items():
    s = (HERE.parent / src).read_text()
    assert s.startswith('"""')
    s = (f'"""v43 Figure {n}: {src} with the type one step larger (generated by make_v43_scripts.py, then laid out again '
         f'by hand). Writes only into figures/cns/v43/.\n' + s[3:])
    s = re.sub(r"\b(fontsize|size)=(\d+(?:\.\d+)?)\b", big, s)
    s = s.replace("FS, FSS = 6.0, 5.6", "FS, FSS = 7.0, 6.5")
    k = s.index("import cns_style as S\n") + len("import cns_style as S\n")
    s = s[:k] + "S.apply_large()\n" + s[k:]
    if stem != f"Fig{n}":
        for a in (f'S.save(fig, "{stem}")', f'"{stem}_numbers.md"'):
            assert s.count(a) == 1, (src, a)
            s = s.replace(a, a.replace(stem, f"Fig{n}"))
    (HERE / f"make_fig{n}.py").write_text(s)
print(sorted(seen.items()))
